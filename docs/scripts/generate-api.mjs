#!/usr/bin/env node
/**
 * Generated API reference for @skygenesisenterprise/react-sds.
 *
 * Source of truth: the built declarations in `dist/**\/*.d.ts` and the package
 * `exports` map. Nothing is inferred from internal `src/` paths, so the
 * reference can only describe what the package actually publishes.
 *
 * Usage:
 *   node scripts/generate-api.mjs           write the pages
 *   node scripts/generate-api.mjs --check   fail if the committed pages are stale
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(docsDir, "..");
const contentDir = path.join(docsDir, "content/docs/api");
const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, "package.json"), "utf8"));
const isCheck = process.argv.includes("--check");

const MARKER =
	"{/* GENERATED by docs/scripts/generate-api.mjs from the package declarations — do not edit. */}";

/** @param {string} spec */
function kebab(spec) {
	return spec
		.replace(/^\.\//, "")
		.replace(/\.d\.ts$/, "")
		.split("/")
		.filter(Boolean)
		.map((segment) =>
			segment
				.replace(/([a-z0-9])([A-Z])/g, "$1-$2")
				.replace(/[^a-zA-Z0-9-]+/g, "-")
				.toLowerCase(),
		)
		.join("-");
}

/** Page slug: the last segment of the entry, so `./sds/portal/SDSHero` → `sdshero`. */
function pageSlug(entry) {
	const segments = entry.replace(/^\.\//, "").split("/").filter(Boolean);
	return kebab(segments[segments.length - 1] ?? entry);
}

/** @param {string} value */
function escapeTable(value) {
	return String(value).replace(/\|/g, "\\|").replace(/\n+/g, " ");
}

/** Inline code span that survives backticks inside TypeScript template literal types. */
function inlineCode(value) {
	const text = String(value).replace(/\|/g, "\\|").replace(/\n+/g, " ");
	if (!text) return "—";
	const runs = text.match(/`+/g) ?? [];
	const fence = "`".repeat(Math.max(0, ...runs.map((run) => run.length)) + 1);
	const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
	return `${fence}${pad}${text}${pad}${fence}`;
}

/** @param {string} value */
function escapeProse(value) {
	return String(value).replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;");
}

const SKIP_PREFIXES = [
	"./legacy/",
	"./picto/",
	"./fr/",
	"./assets/",
	"./styles/",
	"./discord/",
	"./zz_internal/",
];

/** Entry modules that get a generated page, grouped by category. */
function categorise(entry) {
	if (!entry.startsWith("./")) return null;
	if (SKIP_PREFIXES.some((prefix) => entry.startsWith(prefix))) return null;
	if (entry === "./index" || entry === "./package.json") return null;
	if (/\.(css|scss|svg|cjs|js)$/.test(entry)) return null;

	if (entry === "./main.css") return null;

	if (entry.startsWith("./sds/")) return "sds";
	if (entry.startsWith("./native/")) return null; // covered by the React Native guide + exports page
	if (entry.startsWith("./tools/")) return "utilities";
	if (
		entry === "./useColors" ||
		entry === "./useIsDark" ||
		entry === "./useBreakpointsValues" ||
		entry === "./useBreakpointsValuesPx" ||
		entry.startsWith("./consentManagement")
	)
		return "hooks";
	if (/^\.\/[A-Z]/.test(entry) || /^\.\/(Chart|Display|Header|MainNavigation|Modal|SearchBar|blocks|shared)\//.test(entry))
		return "components";
	return null;
}

/** Resolve entry → declaration file path. */
function typesPathOf(value) {
	const target = typeof value === "string" ? value : value?.types;
	if (typeof target !== "string") return null;
	const abs = path.join(repoRoot, target.replace(/^\.\//, ""));
	return fs.existsSync(abs) ? abs : null;
}

const entries = [];
for (const [entry, value] of Object.entries(pkg.exports ?? {})) {
	const category = categorise(entry);
	if (category === null) continue;
	const typesPath = typesPathOf(value);
	if (typesPath === null) continue;
	entries.push({ entry, category, typesPath });
}

// ---------------------------------------------------------------------------
// TypeScript program over the public declarations
// ---------------------------------------------------------------------------

const program = ts.createProgram(
	[...new Set(entries.map((e) => e.typesPath)), path.join(repoRoot, "dist/index.d.ts")],
	{
		noEmit: true,
		skipLibCheck: true,
		moduleResolution: ts.ModuleResolutionKind.NodeJs,
		target: ts.ScriptTarget.ES2019,
		jsx: ts.JsxEmit.React,
		types: [],
	},
);
const checker = program.getTypeChecker();

const rootSource = program.getSourceFile(path.join(repoRoot, "dist/index.d.ts"));
const rootSymbol = rootSource ? checker.getSymbolAtLocation(rootSource) : undefined;
const rootExports = new Set(
	rootSymbol ? checker.getExportsOfModule(rootSymbol).map((symbol) => symbol.getName()) : [],
);

/** @param {ts.Symbol} symbol */
function resolveSymbol(symbol) {
	if (symbol.flags & ts.SymbolFlags.Alias) {
		try {
			return checker.getAliasedSymbol(symbol);
		} catch {
			return symbol;
		}
	}
	return symbol;
}

/** @param {ts.Symbol} symbol */
function docOf(symbol) {
	try {
		return ts.displayPartsToString(resolveSymbol(symbol).getDocumentationComment(checker)).trim();
	} catch {
		return "";
	}
}

/** @param {string} text */
function firstSentence(text) {
	const line = text.split(/\n/)[0].trim();
	if (line.length === 0) return "";
	return line.length > 220 ? `${line.slice(0, 217)}…` : line;
}

/** @param {ts.Symbol} prop */
function defaultOf(prop) {
	const doc = docOf(prop);
	const explicit = /\*?\s*@default(?:Value)?\s+([^\n]+)/i.exec(doc);
	if (explicit) return explicit[1].trim().replace(/\.$/, "");
	const inline = /\bDefault:?\s*([^\n.*]+)/i.exec(doc);
	if (inline) return inline[1].trim();
	return "";
}

/** @param {ts.Symbol} symbol */
function declarationText(symbol) {
	const target = resolveSymbol(symbol);
	const declaration = target.declarations?.[0];
	if (!declaration) return "";
	const source = declaration.getSourceFile();
	return declaration.getText(source);
}

/** @param {ts.Symbol} symbol */
function kindOf(symbol) {
	const declaration = resolveSymbol(symbol).declarations?.[0];
	if (!declaration) return "symbol";
	if (ts.isTypeAliasDeclaration(declaration)) return "type";
	if (ts.isInterfaceDeclaration(declaration)) return "interface";
	if (ts.isFunctionDeclaration(declaration)) return "function";
	if (ts.isVariableDeclaration(declaration)) return "const";
	if (ts.isModuleDeclaration(declaration)) return "namespace";
	if (ts.isClassDeclaration(declaration)) return "class";
	return "symbol";
}

/** Props of a declared type, when it resolves to an object shape. */
function propsOf(symbol) {
	const target = resolveSymbol(symbol);
	const declaration = target.declarations?.[0];
	if (!declaration) return [];

	let props = [];
	try {
		const type = checker.getDeclaredTypeOfSymbol(target);
		const candidates = checker.getPropertiesOfType(checker.getNonNullableType(type));
		if (candidates.length > 0) {
			props = candidates;
		} else if (ts.isTypeAliasDeclaration(declaration)) {
			const members = declaration.type.members;
			if (members && ts.isTypeLiteralNode(declaration.type)) {
				props = members
					.filter(ts.isPropertySignature)
					.map((member) => member.symbol)
					.filter(Boolean);
			}
		}
	} catch {
		return [];
	}

	return props
		.map((prop) => {
			let typeText = "";
			try {
				typeText = checker.typeToString(
					checker.getTypeOfSymbolAtLocation(prop, prop.valueDeclaration ?? declaration),
				);
			} catch {
				typeText = "";
			}
			const optional = (prop.flags & ts.SymbolFlags.Optional) !== 0;
			return {
				name: prop.getName(),
				type: typeText,
				optional,
				default: defaultOf(prop),
				description: firstSentence(docOf(prop)),
			};
		})
		.filter((prop) => !prop.name.startsWith("__"))
		.slice(0, 45);
}

/** @param {{entry: string, category: string, typesPath: string}} item */
function buildPage(item) {
	const source = program.getSourceFile(item.typesPath);
	if (!source) return null;
	const moduleSymbol = checker.getSymbolAtLocation(source);
	if (!moduleSymbol) return null;

	let symbols = [];
	try {
		symbols = checker.getExportsOfModule(moduleSymbol).map((symbol) => {
			const resolved = resolveSymbol(symbol);
			let typeText = "";
			try {
				const declaration = resolved.declarations?.[0];
				typeText = declaration ? checker.typeToString(checker.getTypeOfSymbolAtLocation(resolved, declaration)) : "";
			} catch {
				typeText = "";
			}
			return {
				name: symbol.getName(),
				kind: kindOf(symbol),
				typeText,
				doc: docOf(symbol),
				sourceText: declarationText(symbol),
			};
		});
	} catch {
		return null;
	}
	if (symbols.length === 0) return null;

	const baseName = item.entry.split("/").filter(Boolean).pop() ?? item.entry;
	const primary =
		symbols.find((symbol) => symbol.name === baseName && symbol.kind !== "type") ??
		symbols.find((symbol) => symbol.kind === "const" || symbol.kind === "function") ??
		symbols[0];

	const propsSymbolName = `${primary.name}Props`;
	let propsSymbol = symbols.find((symbol) => symbol.name === propsSymbolName);
	if (!propsSymbol) propsSymbol = symbols.find((symbol) => symbol.name.endsWith("Props") && symbol.kind === "type");

	let props = [];
	if (propsSymbol) {
		const sourceSymbol = checker
			.getExportsOfModule(moduleSymbol)
			.find((symbol) => symbol.getName() === propsSymbol.name);
		if (sourceSymbol) props = propsOf(sourceSymbol);
	}

	const description =
		firstSentence(primary.doc) ||
		`Public API of the ${item.entry} entry of @skygenesisenterprise/react-sds.`;

	const importName = primary.name;
	const isRootExport = rootExports.has(importName);
	const importLines = [];
	if (isRootExport && primary.kind !== "type") {
		importLines.push(`import { ${importName} } from "@skygenesisenterprise/react-sds";`);
	}
	if (primary.kind !== "type") {
		importLines.push(`import { ${importName} } from "@skygenesisenterprise/react-sds/${item.entry.replace(/^\.\//, "")}";`);
	}
	if (importLines.length === 0) {
		importLines.push(`import type { ${importName} } from "@skygenesisenterprise/react-sds/${item.entry.replace(/^\.\//, "")}";`);
	}

	const lines = [];
	lines.push("---");
	lines.push(`title: ${JSON.stringify(importName)}`);
	lines.push(`description: ${JSON.stringify(description)}`);
	lines.push("---");
	lines.push("");
	lines.push(MARKER);
	lines.push("");
	lines.push(`> ${escapeProse(primary.doc || description)}`);
	lines.push("");
	lines.push("## Import");
	lines.push("");
	lines.push("```ts");
	lines.push(...importLines);
	lines.push("```");
	lines.push("");

	if (props.length > 0) {
		lines.push("## Properties");
		lines.push("");
		lines.push("| Property | Type | Required | Default | Description |");
		lines.push("| --- | --- | --- | --- | --- |");
		for (const prop of props) {
			lines.push(
				`| ${inlineCode(prop.name)} | ${inlineCode(prop.type)} | ${prop.optional ? "No" : "Yes"} | ${escapeTable(prop.default) || "—"} | ${escapeTable(prop.description) || "—"} |`,
			);
		}
		lines.push("");
	}

	lines.push("## Exports");
	lines.push("");
	lines.push("| Name | Kind | Type |");
	lines.push("| --- | --- | --- |");
	for (const symbol of symbols) {
		lines.push(
			`| ${inlineCode(symbol.name)} | ${symbol.kind} | ${inlineCode(symbol.typeText.slice(0, 200))} |`,
		);
	}
	lines.push("");

	const declarations = symbols
		.filter((symbol) => ["type", "interface", "namespace"].includes(symbol.kind) && symbol.sourceText)
		.slice(0, 3);
	if (declarations.length > 0) {
		lines.push("## Declaration");
		lines.push("");
		for (const symbol of declarations) {
			const text = symbol.sourceText.split("\n").slice(0, 90).join("\n");
			lines.push(`\`\`\`ts title="${item.entry}"`);
			lines.push(text);
			lines.push("```");
			lines.push("");
		}
	}

	return {
		category: item.category,
		slug: pageSlug(item.entry),
		content: `${lines.join("\n").trimEnd()}\n`,
	};
}

// ---------------------------------------------------------------------------
// Exports page
// ---------------------------------------------------------------------------

function buildExportsPage() {
	const lines = [];
	lines.push("---");
	lines.push('title: "Exports"');
	lines.push(
		'description: "Every entry of the package exports map, generated from the package manifest."',
	);
	lines.push("---");
	lines.push("");
	lines.push(MARKER);
	lines.push("");
	lines.push(
		"> This table is generated from the `exports` field of `package.json`. An entry that is not listed here does not exist in the package.",
	);
	lines.push("");
	lines.push("| Entry | Resolves to |");
	lines.push("| --- | --- |");

	for (const [entry, value] of Object.entries(pkg.exports ?? {})) {
		const target =
			typeof value === "string"
				? value
				: value?.default ?? value?.import ?? value?.require ?? value?.types ?? "";
		lines.push(`| \`@skygenesisenterprise/react-sds${entry.slice(1)}\` | \`${escapeTable(target)}\` |`);
	}
	lines.push("");
	lines.push(`Total: ${Object.keys(pkg.exports ?? {}).length} entries.`);
	return `${lines.join("\n")}\n`;
}

// ---------------------------------------------------------------------------
// Write / check
// ---------------------------------------------------------------------------

const expected = new Map(); // absolute path -> content
const pagesByCategory = new Map();
const usedSlugs = new Set();

for (const item of entries) {
	const page = buildPage(item);
	if (page === null) continue;
	let slug = page.slug;
	if (usedSlugs.has(`${page.category}/${slug}`)) {
		const segments = item.entry.replace(/^\.\//, "").split("/").filter(Boolean);
		slug = kebab(segments.slice(-2).join("-"));
	}
	usedSlugs.add(`${page.category}/${slug}`);
	page.slug = slug;

	const dir = path.join(contentDir, page.category);
	const file = path.join(dir, `${slug}.mdx`);
	if (expected.has(file)) continue;
	expected.set(file, page.content);
	if (!pagesByCategory.has(page.category)) pagesByCategory.set(page.category, []);
	pagesByCategory.get(page.category).push({
		slug,
		title: item.entry.split("/").filter(Boolean).pop(),
		entry: item.entry,
	});
}

expected.set(path.join(contentDir, "exports.mdx"), buildExportsPage());

const CATEGORY_TITLES = {
	components: "Components",
	sds: "SDS components",
	hooks: "Hooks",
	utilities: "Utilities",
};

for (const [category, pages] of pagesByCategory) {
	pages.sort((a, b) => a.title.localeCompare(b.title));
	const title = CATEGORY_TITLES[category] ?? category;
	const meta = {
		title,
		pages: ["index", ...pages.map((page) => page.slug)],
	};
	expected.set(path.join(contentDir, category, "meta.json"), `${JSON.stringify(meta, null, "\t")}\n`);

	const indexLines = [
		"---",
		`title: ${JSON.stringify(title)}`,
		`description: ${JSON.stringify(`Generated reference of the ${title.toLowerCase()} entry points of @skygenesisenterprise/react-sds.`)}`,
		"---",
		"",
		MARKER,
		"",
		`> ${pages.length} modules are exported in this category. Each page is generated from the module declaration.`,
		"",
		"| Module | Entry | Reference |",
		"| --- | --- | --- |",
	];
	for (const page of pages) {
		indexLines.push(
			`| ${page.title} | \`@skygenesisenterprise/react-sds${page.entry.slice(1)}\` | [${page.title}](/docs/api/${category}/${page.slug}) |`,
		);
	}
	indexLines.push("");
	expected.set(path.join(contentDir, category, "index.mdx"), `${indexLines.join("\n")}\n`);
}

if (isCheck) {
	const stale = [];
	for (const [file, content] of expected) {
		if (!fs.existsSync(file)) {
			stale.push(`missing: ${path.relative(docsDir, file)}`);
			continue;
		}
		if (fs.readFileSync(file, "utf8") !== content) {
			stale.push(`outdated: ${path.relative(docsDir, file)}`);
		}
	}
	if (stale.length > 0) {
		console.error("The generated API reference is stale. Run: pnpm --filter @skygenesisenterprise/react-sds-docs generate");
		for (const line of stale) console.error(`  ${line}`);
		process.exit(1);
	}
	console.log(`API reference up to date (${expected.size} generated files).`);
	process.exit(0);
}

// Remove previously generated pages that are no longer expected.
for (const category of ["components", "sds", "hooks", "utilities"]) {
	const dir = path.join(contentDir, category);
	if (!fs.existsSync(dir)) continue;
	for (const name of fs.readdirSync(dir)) {
		const file = path.join(dir, name);
		if (expected.has(file)) continue;
		if (!name.endsWith(".mdx") && name !== "meta.json") continue;
		const content = fs.readFileSync(file, "utf8");
		if (content.includes("GENERATED by docs/scripts/generate-api.mjs")) {
			fs.rmSync(file);
		}
	}
}

for (const [file, content] of expected) {
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, content);
}

console.log(`Generated ${expected.size} API reference files.`);
